using System.IO.Compression;
using System.Text.RegularExpressions;

namespace D2ViewerEditor.Benchmarks;

/// <summary>
/// Structural snapshot of a DOCX package used for fidelity regression checks. Reads the package
/// as a ZIP and counts the elements that matter for document fidelity (styles, numbering, theme,
/// tables, page breaks, row heights). Deliberately parser-independent (raw XML) so it can judge
/// the writer's output objectively.
/// </summary>
public sealed record DocxPackageReport(
    int PartCount,
    int Styles,
    int TableStyles,
    bool HasNumbering,
    bool HasTheme,
    string? ThemeMinorFont,
    bool DocDefaultsUsesTheme,
    int Tables,
    int Rows,
    int Cells,
    int PageBreaks,
    int RowHeights,
    long FileSizeBytes,
    int HtmlLength)
{
    public static DocxPackageReport Analyze(byte[] docx, int htmlLength = 0)
    {
        using var ms = new MemoryStream(docx);
        using var zip = new ZipArchive(ms, ZipArchiveMode.Read);

        // Entry names come from an untrusted package: an entry escaping the archive root
        // ("../word/document.xml") would still satisfy the part matchers below. Drop those
        // before anything is matched or read — same rule as the production upload guard.
        var entries = zip.Entries.Where(e => IsSafeEntryName(e.FullName)).ToList();

        string Read(Predicate<string> match)
        {
            var entry = entries.FirstOrDefault(e => match(e.FullName));
            if (entry == null) return string.Empty;
            using var r = new StreamReader(entry.Open());
            return r.ReadToEnd();
        }
        bool Has(Predicate<string> match) => entries.Any(e => match(e.FullName));

        var styles = Read(n => Regex.IsMatch(n, @"word/styles\d*\.xml$"));
        var doc = Read(n => n.EndsWith("word/document.xml"));
        var theme = Read(n => Regex.IsMatch(n, @"word/theme/theme\d*\.xml$"));

        var minor = Regex.Match(theme, "<a:minorFont>.*?<a:latin typeface=\"([^\"]*)\"", RegexOptions.Singleline);
        var docDefaults = Regex.Match(styles, "<w:docDefaults>.*?<w:rFonts ([^>]*)/>", RegexOptions.Singleline);

        return new DocxPackageReport(
            PartCount: entries.Count,
            Styles: Regex.Matches(styles, "<w:style ").Count,
            TableStyles: Regex.Matches(styles, "<w:style [^>]*w:type=\"table\"").Count,
            HasNumbering: Has(n => n.EndsWith("word/numbering.xml")),
            HasTheme: !string.IsNullOrEmpty(theme),
            ThemeMinorFont: minor.Success ? minor.Groups[1].Value : null,
            DocDefaultsUsesTheme: docDefaults.Success && docDefaults.Groups[1].Value.Contains("Theme"),
            Tables: Regex.Matches(doc, "<w:tbl>").Count,
            Rows: Regex.Matches(doc, "<w:tr[ >]").Count,
            Cells: Regex.Matches(doc, "<w:tc>").Count,
            PageBreaks: Regex.Matches(doc, "<w:br w:type=\"page\"").Count,
            RowHeights: Regex.Matches(doc, "<w:trHeight ").Count,
            FileSizeBytes: docx.LongLength,
            HtmlLength: htmlLength);
    }

    private static bool IsSafeEntryName(string entryName)
    {
        var normalized = entryName.Replace('\\', '/');
        return !normalized.StartsWith('/')
            && !normalized.StartsWith("../", StringComparison.Ordinal)
            && !normalized.Contains("/../", StringComparison.Ordinal)
            && !normalized.Contains(':', StringComparison.Ordinal);
    }
}

public enum FidelityStatus { Pass, Warn, Fail }

public sealed record FidelityCheck(string Name, FidelityStatus Status, string Detail);

/// <summary>
/// Compares an original package with the round-tripped result and grades each fidelity invariant.
/// Thresholds are intentionally lenient (report-first): only a clear loss is FAIL. See
/// <c>.ai/BENCHMARKS.md</c> for which checks are hard gates vs informational.
/// </summary>
public sealed class FidelityComparison
{
    public IReadOnlyList<FidelityCheck> Checks { get; }
    public FidelityStatus Overall => Checks.Count == 0 ? FidelityStatus.Pass : Checks.Max(c => c.Status);

    private FidelityComparison(IReadOnlyList<FidelityCheck> checks) => Checks = checks;

    /// <param name="preservationExpected">
    /// True when the result was produced by the pass-through writer (R-16) — then losing
    /// styles/theme/numbering is a regression. The self-contained writer legitimately regenerates
    /// these (no original to preserve), so for it those checks are informational only.
    /// </param>
    public static FidelityComparison Compare(DocxPackageReport before, DocxPackageReport after, bool preservationExpected)
    {
        var checks = new List<FidelityCheck>();
        var lossStatus = preservationExpected ? FidelityStatus.Fail : FidelityStatus.Pass;
        var softLoss = preservationExpected ? FidelityStatus.Warn : FidelityStatus.Pass;
        var note = preservationExpected ? string.Empty : " (self-contained writer — regenerated by design)";

        // R-16 — styles must not collapse (a from-scratch writer drops them to ~16).
        checks.Add(before.Styles == 0
            ? new("Styles preserved", FidelityStatus.Pass, "original had no styles.xml")
            : after.Styles >= before.Styles * 0.5
                ? new("Styles preserved", FidelityStatus.Pass, $"{before.Styles} → {after.Styles}")
                : new("Styles preserved", lossStatus, $"{before.Styles} → {after.Styles}{note}"));

        checks.Add(before.TableStyles == 0
            ? new("Table styles", FidelityStatus.Pass, "none in original")
            : after.TableStyles >= before.TableStyles
                ? new("Table styles", FidelityStatus.Pass, $"{before.TableStyles} → {after.TableStyles}")
                : new("Table styles", softLoss, $"{before.TableStyles} → {after.TableStyles}{note}"));

        // R-16 — theme/font preservation.
        checks.Add(!before.HasTheme
            ? new("Theme preserved", FidelityStatus.Pass, "no theme in original")
            : after.HasTheme ? new("Theme preserved", FidelityStatus.Pass, "present")
                             : new("Theme preserved", lossStatus, $"theme dropped{note}"));

        checks.Add(before.ThemeMinorFont == null
            ? new("Theme minor font", FidelityStatus.Pass, "n/a")
            : before.ThemeMinorFont == after.ThemeMinorFont
                ? new("Theme minor font", FidelityStatus.Pass, before.ThemeMinorFont)
                : new("Theme minor font", softLoss, $"{before.ThemeMinorFont} → {after.ThemeMinorFont ?? "(none)"}{note}"));

        // Numbering preservation (informational — see R-19; not yet passed through).
        checks.Add(!before.HasNumbering
            ? new("Numbering preserved", FidelityStatus.Pass, "none in original")
            : after.HasNumbering ? new("Numbering preserved", FidelityStatus.Pass, "present")
                                 : new("Numbering preserved", softLoss, $"numbering.xml not carried (R-19){note}"));

        // R-17 — a logical table must not multiply.
        checks.Add(after.Tables <= before.Tables
            ? new("Table count", FidelityStatus.Pass, $"{before.Tables} → {after.Tables}")
            : new("Table count", FidelityStatus.Fail, $"{before.Tables} → {after.Tables} (table split?)"));

        // R-15 — manual page breaks must not be lost or duplicated.
        checks.Add(after.PageBreaks == before.PageBreaks
            ? new("Page breaks", FidelityStatus.Pass, $"{before.PageBreaks}")
            : after.PageBreaks < before.PageBreaks
                ? new("Page breaks", FidelityStatus.Fail, $"{before.PageBreaks} → {after.PageBreaks} (lost)")
                : new("Page breaks", FidelityStatus.Warn, $"{before.PageBreaks} → {after.PageBreaks} (added)"));

        // R-18 — no fabricated row heights beyond the original.
        checks.Add(after.RowHeights <= before.RowHeights + before.Rows
            ? new("Row heights", FidelityStatus.Pass, $"{before.RowHeights} → {after.RowHeights}")
            : new("Row heights", FidelityStatus.Warn, $"{before.RowHeights} → {after.RowHeights} (fabricated?)"));

        // File size — informational only.
        var pct = before.FileSizeBytes == 0 ? 0 : (after.FileSizeBytes - before.FileSizeBytes) * 100.0 / before.FileSizeBytes;
        checks.Add(new("File size", FidelityStatus.Pass, $"{before.FileSizeBytes} → {after.FileSizeBytes} B ({pct:+0.#;-0.#;0}%)"));

        return new FidelityComparison(checks);
    }
}
